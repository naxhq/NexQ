// Writes src-tauri/nsis/release-info.nsh: what the installer shows about the
// version it installs (date, build, what's new, the release's waveform). Runs
// through tauri.conf.json's beforeBundleCommand.

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { formatReleaseDate, parseChangelog } from "../src/lib/releaseNotes.mjs";
import { releaseWave } from "../src/lib/releaseWave.mjs";

/** Rows the installer has room for; the rest is counted as "+N more". */
const MAX_NOTES = 3;
/** Roughly how many characters fit on one line of a note. */
const CHARS_PER_LINE = 50;
const MAX_LINES = 2;

/** Text as a safe NSIS string: `$` and `"` are special, and notes are one line. */
export function nsisString(text) {
  return text
    .replace(/[\r\n\t]+/g, " ")
    .replace(/\$/g, "$$$$")
    .replace(/"/g, '$\\"');
}

function shorten(text, limit) {
  if (text.length <= limit) return text;
  return `${text.slice(0, limit - 1).trimEnd()}…`;
}

export function renderReleaseInfo({ version, changelog, commit, today }) {
  const release = parseChangelog(changelog).find((r) => r.version === version);
  const notes = (release?.sections ?? []).flatMap((section) =>
    section.items.map((text) => ({ tag: section.title, text })),
  );
  const shown = notes.slice(0, MAX_NOTES);
  const released = formatReleaseDate(release?.date ?? today) ?? "";

  const lines = [
    "; Generated by scripts/nsis-release-info.mjs. Don't edit.",
    `!define NQ_INFO_VERSION "${nsisString(version)}"`,
    `!define NQ_RELEASED "${nsisString(released)}"`,
    `!define NQ_BUILD "${nsisString(commit)}"`,
    `!define NQ_NOTES_TOTAL ${notes.length}`,
    `!define NQ_NOTES_MORE ${notes.length - shown.length}`,
    "",
    "!macro NQ_RELEASE_NOTES",
  ];

  for (const { tag, text } of shown) {
    const short = shorten(text, CHARS_PER_LINE * MAX_LINES);
    const rows = Math.min(MAX_LINES, Math.ceil(short.length / CHARS_PER_LINE));
    lines.push(`  !insertmacro NqNote "${nsisString(tag)}" "${nsisString(short)}" ${rows}`);
  }

  lines.push("!macroend", "", "!macro NQ_WAVE UN");
  for (const bar of releaseWave(version, 72)) {
    lines.push(`  !insertmacro NqBar "\${UN}" ${Math.round(bar * 100)}`);
  }
  lines.push("!macroend", "");

  return lines.join("\r\n");
}

function main() {
  const root = fileURLToPath(new URL("../", import.meta.url));
  const version = JSON.parse(readFileSync(`${root}package.json`, "utf8")).version;
  const changelog = readFileSync(`${root}CHANGELOG.md`, "utf8");

  let commit = "dev";
  try {
    commit = execFileSync("git", ["rev-parse", "--short=7", "HEAD"], {
      cwd: root,
      encoding: "utf8",
    }).trim();
  } catch {
    // Not a git checkout: the build still works, it just can't name the commit.
  }

  const info = renderReleaseInfo({
    version,
    changelog,
    commit,
    today: new Date().toISOString().slice(0, 10),
  });
  // The byte order mark tells makensis the file is UTF-8.
  writeFileSync(`${root}src-tauri/nsis/release-info.nsh`, `﻿${info}`);
  console.log(`Installer release info written for ${version}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main();
}
